// 2D Point in Triangle collision test
inline bool pointInTriangle(glm::vec2 pt, glm::vec2 v1, glm::vec2 v2, glm::vec2 v3) {
    auto sign = [](glm::vec2 p1, glm::vec2 p2, glm::vec2 p3) {
        return (p1.x - p3.x) * (p2.y - p3.y) - (p2.x - p3.x) * (p1.y - p3.y);
    };
    float d1 = sign(pt, v1, v2);
    float d2 = sign(pt, v2, v3);
    float d3 = sign(pt, v3, v1);
    bool has_neg = (d1 < -0.001f) || (d2 < -0.001f) || (d3 < -0.001f);
    bool has_pos = (d1 > 0.001f) || (d2 > 0.001f) || (d3 > 0.001f);
    return !(has_neg && has_pos);
}

class FontRenderer {
public:
    static float getTextWidth(const std::string& text, float size) {
        float w = 0.0f;
        for (char c : text) {
            if (c == ' ') w += size * 0.45f;
            else w += size * 0.65f;
        }
        return w;
    }

    static void drawText(std::vector<ChunkVertex>& vertices,
                         std::vector<uint32_t>& indices,
                         const std::string& text,
                         float x, float y, float size,
                         const glm::vec3& color = glm::vec3(1.0f),
                         bool withShadow = true,
                         float alpha = 1.0f) {
        float charW = size * 0.85f;
        float charH = size;
        float curX = x;

        auto addGlyphQuad = [&](float gx, float gy, glm::vec4 uv, glm::vec3 col) {
            uint32_t b = static_cast<uint32_t>(vertices.size());
            glm::vec3 norm(0.0f, 0.0f, alpha);
            vertices.push_back({glm::vec3(gx, gy + charH, 0.0f), glm::vec2(uv.x, uv.w), norm, col});
            vertices.push_back({glm::vec3(gx + charW, gy + charH, 0.0f), glm::vec2(uv.z, uv.w), norm, col});
            vertices.push_back({glm::vec3(gx + charW, gy, 0.0f), glm::vec2(uv.z, uv.y), norm, col});
            vertices.push_back({glm::vec3(gx, gy, 0.0f), glm::vec2(uv.x, uv.y), norm, col});

            indices.push_back(b + 0); indices.push_back(b + 1); indices.push_back(b + 2);
            indices.push_back(b + 2); indices.push_back(b + 3); indices.push_back(b + 0);
        };

        for (char c : text) {
            if (c == ' ') {
                curX += size * 0.45f;
                continue;
            }
            if (c < 32 || c > 126) c = '?';

            glm::vec4 uv = TextureAtlas::getTileUV(TextureAtlas::getFontTile(c));

            if (withShadow) {
                float shadowOff = size * 0.10f;
                addGlyphQuad(curX + shadowOff, y + shadowOff, uv, color * 0.20f);
            }
            addGlyphQuad(curX, y, uv, color);

            curX += size * 0.65f;
        }
    }
};

